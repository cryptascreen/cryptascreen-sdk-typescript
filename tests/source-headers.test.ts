// Guard: every source file starts with the two-line CryptaCount, Inc. header in its own comment syntax (after a shebang).
// Skipped: dependencies, build output, test fixtures, data/locale JSON and files marked as generated.
import { describe, it, expect } from 'vitest';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const L1 = 'Copyright (c) 2024-2026 CryptaCount, Inc.';
const L2 = 'SPDX-License-Identifier: MIT';
const STYLE = { '.ts': '//', '.tsx': '//', '.mts': '//', '.cts': '//', '.js': '//', '.mjs': '//', '.cjs': '//', '.jsx': '//' };
const SKIP = /(^|\/)(node_modules|target|dist|coverage|\.git|vendor|third_party)\/|^(build|out)\/|(^|\/)tests?\/fixtures\//;
const GENERATED = /@generated|auto-?generated|do not edit|generated by/i;
const PREAMBLE = /^(#!|#.*coding[:=]|#\s*(syntax|escape|check)=)/;

export function styleOf(file) {
  const base = file.split('/').pop();
  if (base === 'Dockerfile') return '#';
  const i = base.lastIndexOf('.');
  return i < 0 ? undefined : STYLE[base.slice(i).toLowerCase()];
}
const wrap = (st, t) => (st === '/*' ? `/* ${t} */` : `${st} ${t}`);

/** null = carries the header or exempt; otherwise the reason. */
export function problem(file, content) {
  const st = styleOf(file);
  if (!st || SKIP.test(file)) return null;
  const lines = content.replace(/^\uFEFF/, '').split(/\r?\n/);
  if (lines.slice(0, 6).some((l) => GENERATED.test(l))) return null;
  let i = 0;
  while (i < lines.length && PREAMBLE.test(lines[i])) i++;
  return lines[i] === wrap(st, L1) && lines[i + 1] === wrap(st, L2) ? null : 'missing or wrong header';
}

describe('source headers', () => {
  it('every source file starts with the header', () => {
    const root = path.resolve(__dirname, '..');
    const files = execFileSync('git', ['ls-files', '-z', '--', '.'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
    const bad = [];
    let checked = 0;
    for (const f of files) {
      if (!styleOf(f) || !fs.existsSync(path.join(root, f))) continue;
      checked++;
      const why = problem(f, fs.readFileSync(path.join(root, f), 'utf8'));
      if (why) bad.push(`${f}: ${why}`);
    }
    expect(checked).toBeGreaterThan(20);
    expect(bad).toEqual([]);
  });

  it('the rules catch a missing or wrong-holder header', () => {
    expect(problem('src/a.ts', `// ${L1}\n// ${L2}\nexport {};\n`)).toBeNull();
    expect(problem('src/a.ts', 'export {};\n')).not.toBeNull();
    expect(problem('src/a.ts', '// Copyright (c) 2024-2026 CryptaScreen Inc. All Rights Reserved.\nexport {};\n')).not.toBeNull();
    expect(problem('scripts/x.mjs', `#!/usr/bin/env node\r\n// ${L1}\r\n// ${L2}\r\n`)).toBeNull();
    expect(problem('src/a.css', `/* ${L1} */\n/* ${L2} */\n`)).toBeNull();
    expect(problem('public/locales/de/nav.json', '{}')).toBeNull();
  });
});
